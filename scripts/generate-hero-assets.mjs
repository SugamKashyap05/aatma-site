/**
 * Generates src/assets/hero/generated.ts from manifest.json.
 *
 * We emit explicit static imports rather than using import.meta.glob: the glob
 * form with `query: "?url"` did not resolve to hashed build URLs under this
 * Vite/rolldown version (it emitted raw /src/... dev paths), which left the
 * hero with no images and crashed the render.
 *
 * Explicit imports are version-proof and give the bundler a real dependency
 * edge per file, so every variant is emitted and fingerprinted correctly.
 *
 * Run after optimize-hero-images.mjs (or via `npm run hero:build`).
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const HERO_DIR = path.join(ROOT, "src", "assets", "hero");
const MANIFEST = path.join(HERO_DIR, "manifest.json");
const OUT = path.join(HERO_DIR, "generated.ts");

/** Turn "mountain-10-1920" into a safe JS identifier: mountain_10_1920 */
const ident = (s) => s.replace(/[^a-zA-Z0-9]/g, "_").replace(/^(\d)/, "_$1");

async function main() {
  const manifest = JSON.parse(await readFile(MANIFEST, "utf8"));

  const lines = [];
  const entries = [];

  lines.push("// AUTO-GENERATED by scripts/generate-hero-assets.mjs — do not edit by hand.");
  lines.push("// Explicit imports so Vite emits + fingerprints every variant.");
  lines.push("");

  for (const layer of manifest) {
    for (const v of layer.variants) {
      const stem = `${layer.name}-${v.w}`;
      const id = ident(stem);
      lines.push(`import ${id}_webp from "./${stem}.webp";`);
      lines.push(`import ${id}_avif from "./${stem}.avif";`);
    }
  }

  lines.push("");
  lines.push("/** stem -> fingerprinted URLs, e.g. \"bg-1920\" -> { webp, avif } */");
  lines.push("export const HERO_ASSET_URLS: Record<string, { webp: string; avif: string }> = {");
  for (const layer of manifest) {
    for (const v of layer.variants) {
      const stem = `${layer.name}-${v.w}`;
      const id = ident(stem);
      entries.push(stem);
      lines.push(`  "${stem}": { webp: ${id}_webp, avif: ${id}_avif },`);
    }
  }
  lines.push("};");
  lines.push("");

  await writeFile(OUT, lines.join("\n"));
  console.log(`generated.ts written — ${entries.length} variants (${entries.length * 2} imports)`);
}

main().catch((e) => {
  console.error("FAILED:", e.message);
  process.exit(1);
});
